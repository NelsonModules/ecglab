function group = ecgLabBeatCardObjects(figure, state, colour)
  % The class card and intervals card, in one panel on the right: the AAMI
  % class badge, the feature bars, then the beat's intervals. Every row is a
  % fixed pool placed by the mover.
  axesHandle = axes('Parent', figure, 'Units', 'normalized', ...
  'Position', [0.660, 0.090, 0.305, 0.830], 'Tag', 'ecglab.beat.card');
  set(axesHandle, 'XLim', [0, 1], 'YLim', [0, 1], 'XTick', [], 'YTick', [], ...
  'Color', colour.background, 'Box', 'on', 'XColor', colour.frame, ...
  'YColor', colour.frame);
  group = struct('axes', axesHandle);
  % The badge and the class naming.
  group.badge = patch('Parent', axesHandle, 'XData', [0.04 0.13 0.13 0.04], ...
  'YData', [0.905 0.905 0.975 0.975], 'FaceColor', colour.dim, ...
  'EdgeColor', 'none');
  group.badgeText = text(axesHandle, 0.085, 0.940, '', 'Color', ...
  colour.background, 'FontSize', 14, 'FontWeight', 'bold', ...
  'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle', ...
  'Tag', 'ecglab.beat.card.badge');
  group.name = text(axesHandle, 0.16, 0.955, '', 'Color', colour.ink, ...
  'FontSize', 12, 'FontWeight', 'bold', 'VerticalAlignment', 'middle');
  group.conf = text(axesHandle, 0.16, 0.918, '', 'Color', colour.dim, ...
  'FontSize', 9, 'VerticalAlignment', 'middle');
  %===========================================================================
  % The feature rows, one per interpretable feature the model used.
  group.featHead = text(axesHandle, 0.04, 0.855, ...
  'FEATURES THE DECISION RESTED ON', 'Color', colour.dim, 'FontSize', 8, ...
  'FontWeight', 'bold', 'VerticalAlignment', 'middle');
  nFeat = numel(state.featureRows);
  group.featLabel = [];
  group.featTrack = [];
  group.featFill = [];
  group.featValue = [];
  top = 0.810;
  pitch = 0.048;
  for index = 1:nFeat
    y = top - (index - 1) * pitch;
    [lbl, track, fill, value] = ecgLabBeatRow(axesHandle, colour, y, ...
    colour.ink);
    group.featLabel = [group.featLabel, lbl];
    group.featTrack = [group.featTrack, track];
    group.featFill = [group.featFill, fill];
    group.featValue = [group.featValue, value];
  end
  %===========================================================================
  % A divider, then the intervals of the beat.
  dividerY = top - nFeat * pitch - 0.010;
  group.divider = line('Parent', axesHandle, 'XData', [0.04 0.96], ...
  'YData', [dividerY dividerY], 'Color', colour.frame, 'LineWidth', 0.8);
  group.ivHead = text(axesHandle, 0.04, dividerY - 0.030, 'INTERVALS', ...
  'Color', colour.dim, 'FontSize', 8, 'FontWeight', 'bold', ...
  'VerticalAlignment', 'middle');
  ivNames = {'PR', 'QRS', 'QT', 'QTc (Bazett)', 'RR'};
  group.ivName = ivNames;
  group.ivLabel = [];
  group.ivTrack = [];
  group.ivFill = [];
  group.ivValue = [];
  ivTop = dividerY - 0.075;
  for index = 1:numel(ivNames)
    y = ivTop - (index - 1) * pitch;
    [lbl, track, fill, value] = ecgLabBeatRow(axesHandle, colour, y, ...
    colour.calibration);
    set(lbl, 'String', ivNames{index});
    group.ivLabel = [group.ivLabel, lbl];
    group.ivTrack = [group.ivTrack, track];
    group.ivFill = [group.ivFill, fill];
    group.ivValue = [group.ivValue, value];
  end
end
%=============================================================================
function [label, track, fill, value] = ecgLabBeatRow(axesHandle, colour, y, ...
  fillColour)
  % One labelled bar row of a card: a name on the left, a track the bar fills,
  % the value on the right. The fill is the one object the mover resizes.
  half = 0.016;
  label = text(axesHandle, 0.04, y, '', 'Color', colour.ink, 'FontSize', 9, ...
  'VerticalAlignment', 'middle');
  track = patch('Parent', axesHandle, 'XData', [0.40 0.74 0.74 0.40], ...
  'YData', y + [-half -half half half], 'FaceColor', colour.gridMinor, ...
  'EdgeColor', 'none');
  fill = patch('Parent', axesHandle, 'XData', [0.40 0.40 0.40 0.40], ...
  'YData', y + [-half -half half half], 'FaceColor', fillColour, ...
  'EdgeColor', 'none');
  value = text(axesHandle, 0.96, y, '', 'Color', colour.ink, 'FontSize', 9, ...
  'HorizontalAlignment', 'right', 'VerticalAlignment', 'middle');
end
%=============================================================================
function axesHandle = ecgLabBeatPlain(figure, position, colour)
  % A plain axis for text only: no frame, no ticks, the page colour, a unit square.
  axesHandle = axes('Parent', figure, 'Units', 'normalized', ...
  'Position', position);
  set(axesHandle, 'XLim', [0, 1], 'YLim', [0, 1], 'XTick', [], 'YTick', [], ...
  'Color', colour.background, 'XColor', colour.background, ...
  'YColor', colour.background, 'Box', 'off');
end
%=============================================================================
function handle = ecgLabBeatLine(axesHandle, colour, style, width, tag)
  handle = line('Parent', axesHandle, 'XData', NaN, 'YData', NaN, ...
  'Color', colour, 'LineStyle', style, 'LineWidth', width, 'Tag', tag);
end
%=============================================================================
function handle = ecgLabBeatText(axesHandle, colour, points, halign, valign)
  handle = text(axesHandle, 0, 0, '', 'Color', colour, 'FontSize', points, ...
  'HorizontalAlignment', halign, 'VerticalAlignment', valign);
end
