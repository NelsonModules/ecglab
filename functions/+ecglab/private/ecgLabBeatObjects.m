function handles = ecgLabBeatObjects(figure, state)
  % Create every object the beat view holds, once, with placeholder data, and
  % return their handles. Nothing is created later: ecgLabBeatMove only moves
  % these, so the fixed pools are all sized here.
  colour = state.colour;
  trace = state.trace;
  handles = struct();
  %===========================================================================
  % The header: the record on the left, the beat's place in it on the right.
  % The footer always states this is not a clinical record.
  handles.head = ecgLabBeatPlain(figure, [0.035, 0.945, 0.930, 0.045], colour);
  handles.title = text(handles.head, 0.0, 0.5, '', 'Color', colour.ink, ...
  'FontSize', 11, 'FontWeight', 'bold', 'VerticalAlignment', 'middle');
  handles.position = text(handles.head, 1.0, 0.5, '', 'Color', colour.dim, ...
  'FontSize', 10, 'HorizontalAlignment', 'right', ...
  'VerticalAlignment', 'middle');
  handles.foot = ecgLabBeatPlain(figure, [0.035, 0.008, 0.930, 0.028], colour);
  text(handles.foot, 0.0, 0.5, ['Research software, not a medical device. ' ...
  'ecglab is for research and education, not for clinical diagnosis, ' ...
  'monitoring or treatment.'], 'Color', colour.dim, 'FontSize', 8, ...
  'VerticalAlignment', 'middle');
  %===========================================================================
  handles.trace = ecgLabBeatTraceObjects(figure, state, colour, trace);
  handles.evidence = ecgLabBeatEvidenceObjects(figure, state, colour);
  handles.card = ecgLabBeatCardObjects(figure, state, colour);
  handles.controls = struct();
end
%=============================================================================
function group = ecgLabBeatTraceObjects(figure, state, colour, trace)
  % The trace axis, in millimetres like the strip, with the calibrated grid
  % ruled in once. A band above holds the peak labels, one below the brackets.
  axesHandle = axes('Parent', figure, 'Units', 'normalized', ...
  'Position', [0.035, 0.40, 0.600, 0.520], 'Tag', 'ecglab.beat.trace');
  Htot = trace.Hgrid + trace.bracketArea;
  set(axesHandle, 'XLim', [0, trace.Wmm], 'YLim', [-trace.labelArea, Htot], ...
  'YDir', 'reverse', 'XTick', [], 'YTick', [], 'Color', colour.background, ...
  'Box', 'off', 'Clipping', 'on');
  set(axesHandle, 'XColor', colour.background, 'YColor', colour.background);
  % The grid, ruled by the shared primitive over the grid band only.
  grid = ecgLabDrawGrid(axesHandle, [0, trace.Wmm, 0, trace.Hgrid], colour);
  group = struct('axes', axesHandle, 'grid', grid);
  group.signal = ecgLabBeatLine(axesHandle, colour.trace, '-', 0.9, ...
  'ecglab.beat.trace.signal');
  % The fiducial ticks as one broken line and the peak dots as one line of
  % markers, never an object per wave.
  group.ticks = ecgLabBeatLine(axesHandle, colour.dim, '-', 0.6, ...
  'ecglab.beat.trace.ticks');
  group.dots = line('Parent', axesHandle, 'XData', NaN, 'YData', NaN, ...
  'LineStyle', 'none', 'Marker', 'o', 'MarkerSize', 4, ...
  'MarkerFaceColor', colour.calibration, 'MarkerEdgeColor', ...
  colour.calibration, 'Color', colour.calibration, ...
  'Tag', 'ecglab.beat.trace.dots');
  % The three peak labels P, R, T, and the three interval brackets with their
  % labels: a fixed pool, placed by the mover.
  group.peakLabels = [ ...
  ecgLabBeatText(axesHandle, colour.ink, 9, 'center', 'bottom'), ...
  ecgLabBeatText(axesHandle, colour.ink, 9, 'center', 'bottom'), ...
  ecgLabBeatText(axesHandle, colour.ink, 9, 'center', 'bottom')];
  group.brackets = [ ...
  ecgLabBeatLine(axesHandle, colour.dim, '-', 1.0, 'ecglab.beat.trace.bracket'), ...
  ecgLabBeatLine(axesHandle, colour.dim, '-', 1.0, 'ecglab.beat.trace.bracket'), ...
  ecgLabBeatLine(axesHandle, colour.dim, '-', 1.0, 'ecglab.beat.trace.bracket')];
  group.bracketLabels = [ ...
  ecgLabBeatText(axesHandle, colour.dim, 8, 'center', 'top'), ...
  ecgLabBeatText(axesHandle, colour.dim, 8, 'center', 'top'), ...
  ecgLabBeatText(axesHandle, colour.dim, 8, 'center', 'top')];
end
