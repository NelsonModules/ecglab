function group = ecgLabBeatEvidenceObjects(figure, state, colour)
  % The evidence lane under the trace, on the same horizontal window and sharing
  % its left edge and width so samples line up. The feature and threshold are
  % plotted as a fraction of the series maximum, so the lane never rescales.
  axesHandle = axes('Parent', figure, 'Units', 'normalized', ...
  'Position', [0.035, 0.090, 0.600, 0.235], 'Tag', 'ecglab.beat.evidence');
  set(axesHandle, 'YLim', [0, 1.08], 'XLim', [0, 1], 'XTick', [], ...
  'YTick', [], 'Color', colour.background, 'Box', 'on', ...
  'XColor', colour.frame, 'YColor', colour.frame);
  group = struct('axes', axesHandle);
  group.label = text(axesHandle, 0.012, 1.02, '', 'Units', 'normalized', ...
  'Color', colour.dim, 'FontSize', 8, 'FontWeight', 'bold', ...
  'VerticalAlignment', 'top', 'HorizontalAlignment', 'left');
  group.feature = ecgLabBeatLine(axesHandle, colour.classV, '-', 1.4, ...
  'ecglab.beat.evidence.feature');
  group.threshold = ecgLabBeatLine(axesHandle, colour.classS, '--', 1.2, ...
  'ecglab.beat.evidence.threshold');
  group.peak = line('Parent', axesHandle, 'XData', NaN, 'YData', NaN, ...
  'LineStyle', 'none', 'Marker', 'o', 'MarkerSize', 6, ...
  'MarkerFaceColor', 'none', 'MarkerEdgeColor', colour.ink, ...
  'LineWidth', 1.2, 'Color', colour.ink, 'Tag', 'ecglab.beat.evidence.peak');
end
